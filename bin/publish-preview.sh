#!/usr/bin/env bash
# Publishes the WordPress Playground preview and prints a shareable link.
#
# Builds dist/vobrothers-playground.zip (bin/playground-bundle.sh) and force-pushes it,
# with a Playground blueprint, as the single commit on the `playground-preview` branch.
# Keeping it off `main` stops each 40 MB rebuild from piling up in the main history.
# Requires a PUBLIC GitHub repo (Playground downloads the files anonymously).
#
# Usage: bin/setup.sh && bin/publish-preview.sh
set -euo pipefail
cd "$(dirname "$0")/.."

BRANCH=playground-preview
REPO="$(git remote get-url origin | sed -E 's#(https://github.com/|git@github.com:)##; s#\.git$##')"
RAW="https://raw.githubusercontent.com/$REPO/$BRANCH"

bin/playground-bundle.sh

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT
cp dist/vobrothers-playground.zip "$stage/"
cat > "$stage/blueprint.json" <<EOF
{
	"\$schema": "https://playground.wordpress.net/blueprint-schema.json",
	"meta": {
		"title": "VO Brothers Mechanical — website preview",
		"author": "VO Brothers Mechanical"
	},
	"landingPage": "/",
	"preferredVersions": { "php": "8.3", "wp": "latest" },
	"steps": [
		{
			"step": "importWordPressFiles",
			"wordPressFilesZip": { "resource": "url", "url": "$RAW/vobrothers-playground.zip" }
		},
		{
			"step": "updateUserMeta",
			"userId": 1,
			"meta": { "show_admin_bar_front": "false" }
		}
	]
}
EOF
cat > "$stage/README.md" <<EOF
# VO Brothers Mechanical — Playground preview

Generated by \`bin/publish-preview.sh\` on the \`main\` branch. Do not edit here.

Open the preview: https://playground.wordpress.net/?mode=seamless&blueprint-url=$RAW/blueprint.json
EOF

# One-commit branch, replaced on every publish.
git -C "$stage" init -q -b "$BRANCH"
git -C "$stage" add -A
git -C "$stage" -c user.name="$(git config user.name || echo preview)" -c user.email="$(git config user.email || echo preview@localhost)" \
	commit -qm "Playground preview build from main@$(git rev-parse --short HEAD)"
git -C "$stage" push -q --force "$(git remote get-url origin)" "$BRANCH:$BRANCH"

echo "Preview link:"
echo "https://playground.wordpress.net/?mode=seamless&blueprint-url=$RAW/blueprint.json"
